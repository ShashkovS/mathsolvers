class Test(unittest.TestCase):
    pass


def add_test_methods():
    for i, (input_text, expected) in enumerate(cases):
        # Определяем тестовый метод с фиксацией аргументов по умолчанию
        def test_parse_ru_number(self, input_text=input_text, expected=expected):
            result = replace_ru_numbers(input_text)
            self.assertEqual(result.strip(), expected, f"'{input_text}': `{result}` != `{expected}`")

        # Задаём уникальное имя метода
        test_parse_ru_number.__name__ = tests_wrapper.tnesc(f'test_parse_ru_number_{i + 1:03}: {input_text} {expected}')
        setattr(Test, test_parse_ru_number.__name__, test_parse_ru_number)


add_test_methods()

if __name__ == '__main__':
    unittest.main()
