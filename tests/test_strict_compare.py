class Test(tests_wrapper.TestSolver):
    pass


def add_test_methods():
    for i, (expr1, expr2, ans) in enumerate(cases):
        def test_strict_compare(self, expr1=expr1, expr2=expr2, ans=ans):
            res = mathsolvers.strict_compare(expr1, expr2)
            self.assertEqual(int(res), int(ans))

        test_strict_compare.__name__ = tests_wrapper.tnesc(f'test_strict_compare_{i + 1:03}: {expr1} {expr2}')
        setattr(Test, test_strict_compare.__name__, test_strict_compare)


add_test_methods()

