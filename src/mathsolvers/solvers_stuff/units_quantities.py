class DECL(enum.IntEnum):
    NOM = 0
    GEN = 1
    DAT = 2
    ACC = 3
    INS = 4
    PRE = 5
    # Plural
    PNOM = 7
    PGEN = 8
    PDAT = 9
    PACC = 10
    PINS = 11
    PPRE = 12


def get_declension_by_number(number: int) -> DECL:
    if number != int(number):
        return DECL.PGEN
    number = int(number)
    last_digit = number % 10
    last_two_digits = number % 100
    if 11 <= last_two_digits <= 14:
        return DECL.PGEN
    if last_digit == 1:
        return DECL.NOM
    if last_digit in {2, 3, 4}:
        return DECL.GEN
    return DECL.PGEN


def get_prepositional_declension_by_number(number: float) -> DECL:
    # Проверяем, если число дробное, используем множественный предложный падеж
    if number != int(number):
        return DECL.PPRE

    number = int(number)
    last_digit = number % 10
    last_two_digits = number % 100

    if 11 <= last_two_digits <= 14:
        return DECL.PPRE
    if last_digit == 1:
        return DECL.PRE
    return DECL.PPRE


